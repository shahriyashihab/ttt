/**
 * Resolves any image URL (including old /src/assets/images/... URLs stored in Firebase RTDB)
 * to a 100% reliable image that will never throw 404 on any static or free hosting.
 */
export function resolveBotImage(image?: string, category?: string): string {
  if (!image) {
    return getCategoryFallback(category);
  }

  // If already a valid data URI or external URL, return as is
  if (image.startsWith('data:') || image.startsWith('http://') || image.startsWith('https://')) {
    return image;
  }

  // If it points to an old source path like /src/assets/images/...
  const lower = image.toLowerCase();
  if (lower.includes('shop') || lower.includes('ecommerce')) {
    return BOT_IMAGES.ecommerce;
  }
  if (lower.includes('file') || lower.includes('media') || lower.includes('storage')) {
    return BOT_IMAGES.fileStorage;
  }
  if (lower.includes('channel') || lower.includes('manager') || lower.includes('guard')) {
    return BOT_IMAGES.channelGuard;
  }
  if (lower.includes('hero')) {
    return BOT_IMAGES.hero;
  }

  return getCategoryFallback(category);
}

export function getCategoryFallback(category?: string): string {
  switch (category) {
    case 'File & Media Store':
      return BOT_IMAGES.fileStorage;
    case 'Channel & Group':
      return BOT_IMAGES.channelGuard;
    case 'Payment & Crypto':
    case 'Utility & AI':
    case 'E-Commerce & Shop':
    default:
      return BOT_IMAGES.ecommerce;
  }
}
